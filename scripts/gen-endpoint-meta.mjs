#!/usr/bin/env node
/**
 * Emit packages/api/src/endpoint-meta.gen.ts from the pinned upstream endpoints:
 * the ApiCallService gate fields (secure, kind, requireCredential, requireModerator,
 * requireAdmin), the rate `limit` (duration / max / minInterval / key, in ms) and the HTTP
 * caching fields (`allowGet`, `cacheSec`) of every endpoint in endpoint-list.ts.
 * Re-run after bumping upstream.
 *
 * Usage: node scripts/gen-endpoint-meta.mjs [--check]
 *   --check: exit 1 when the committed file is stale.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backend = resolve(root, "upstream/misskey/packages/backend/src/server/api");
const out = resolve(root, "packages/api/src/endpoint-meta.gen.ts");

const list = readFileSync(resolve(backend, "endpoint-list.ts"), "utf8");
const names = [...list.matchAll(/from '\.\/endpoints\/(.+?)\.js'/g)].map((m) => m[1]);
if (names.length === 0) {
  console.error("gen-endpoint-meta: no endpoints found (is the upstream submodule checked out?)");
  process.exit(2);
}

/** `ms('1hour')`-style durations as used in upstream endpoint metas. */
const MS_UNITS = { ms: 1, s: 1000, sec: 1000, m: 60_000, min: 60_000, h: 3_600_000, hour: 3_600_000, hours: 3_600_000, d: 86_400_000, day: 86_400_000, days: 86_400_000 };
function evalLimitValue(raw, where) {
  const expr = raw.trim().replace(/ms\((['"])(\d+(?:\.\d+)?)\s*([a-z]+)\1\)/g, (_, _q, n, u) => {
    if (!(u in MS_UNITS)) throw new Error(`gen-endpoint-meta: unknown ms() unit '${u}' in ${where}`);
    return String(Number(n) * MS_UNITS[u]);
  });
  if (!/^[\d\s*+\-/().]+$/.test(expr)) throw new Error(`gen-endpoint-meta: cannot evaluate limit value '${raw}' in ${where}`);
  return Function(`"use strict"; return (${expr});`)();
}

/** The `limit: { ... }` block of an endpoint meta (one-tab indent), or null. */
function parseLimit(block, where) {
  const m = /\n\tlimit: \{([\s\S]*?)\n\t\},/.exec(block);
  if (!m) return null;
  const limit = {};
  for (const line of m[1].split("\n")) {
    const kv = /^\t\t(\w+): (.+?),?$/.exec(line);
    if (!kv) continue;
    const [, k, v] = kv;
    if (k === "key") limit.key = /^['"](.+)['"]$/.exec(v.trim())?.[1];
    else if (k === "duration" || k === "max" || k === "minInterval") limit[k] = evalLimitValue(v, where);
    else throw new Error(`gen-endpoint-meta: unknown limit key '${k}' in ${where}`);
  }
  return limit;
}

const meta = {};
for (const name of names) {
  const file = resolve(backend, "endpoints", `${name}.ts`);
  if (!existsSync(file)) continue;
  const src = readFileSync(file, "utf8");
  const start = src.indexOf("export const meta = {");
  const end = src.indexOf("\n} as const;", start);
  if (start < 0 || end < 0) continue;
  const block = src.slice(start, end);
  // top-level keys of the meta object are indented with exactly one tab
  const flag = (k) => new RegExp(`\\n\\t${k}: true,`).test(block);
  const kind = /\n\tkind: ['"]([^'"]+)['"],/.exec(block)?.[1];
  const m = {};
  if (flag("requireCredential")) m.requireCredential = true;
  if (flag("requireModerator")) m.requireModerator = true;
  if (flag("requireAdmin")) m.requireAdmin = true;
  if (flag("secure")) m.secure = true;
  if (flag("prohibitMoved")) m.prohibitMoved = true;
  if (kind) m.kind = kind;
  const requiredRolePolicy = /\n\trequiredRolePolicy: ['"]([^'"]+)['"],/.exec(block)?.[1];
  if (requiredRolePolicy) m.requiredRolePolicy = requiredRolePolicy;
  const limit = parseLimit(block, name);
  if (limit) m.limit = limit;
  if (flag("allowGet")) m.allowGet = true;
  const cacheSec = /\n\tcacheSec: (.+?),(?:\n|$)/.exec(block)?.[1];
  if (cacheSec) m.cacheSec = evalLimitValue(cacheSec, name);
  meta[name] = m;
}

const body = `// Generated by scripts/gen-endpoint-meta.mjs from upstream/misskey — do not edit.
/* eslint-disable */

export type EndpointGateMeta = {
  requireCredential?: true;
  requireModerator?: true;
  requireAdmin?: true;
  secure?: true;
  /** ApiCallService: refused with YOUR_ACCOUNT_MOVED for a moved account */
  prohibitMoved?: true;
  kind?: string;
  /** role policy that must be true (root and administrators pass) */
  requiredRolePolicy?: string;
  /** upstream meta.limit (ms); the key defaults to the endpoint name */
  limit?: { duration?: number; max?: number; minInterval?: number; key?: string };
  /** upstream meta.allowGet: GET is accepted (otherwise 405) */
  allowGet?: true;
  /** upstream meta.cacheSec: \`Cache-Control: public, max-age\` for anonymous GET */
  cacheSec?: number;
};

export const ENDPOINT_META: Readonly<Record<string, EndpointGateMeta>> = ${JSON.stringify(meta, null, 2)};
`;

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== body) {
    console.error("gen-endpoint-meta: packages/api/src/endpoint-meta.gen.ts is stale; run node scripts/gen-endpoint-meta.mjs");
    process.exit(1);
  }
  console.log(`gen-endpoint-meta: up to date (${Object.keys(meta).length} endpoints)`);
} else {
  writeFileSync(out, body);
  console.log(`gen-endpoint-meta: wrote ${Object.keys(meta).length} endpoints`);
}
