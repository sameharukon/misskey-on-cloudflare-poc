#!/usr/bin/env node
/**
 * Generate local wrangler configs for one federation test environment.
 *
 *   node scripts/fed-local/gen-config.mjs <env> <host> <databaseUrl> <setupPassword>
 *
 * Writes packages/<worker>/wrangler.fed-<env>.toml (gitignored) for gateway / api / stream /
 * timeline. Worker names get a per-environment prefix so two `wrangler dev` processes never
 * resolve each other's workers through the local dev registry. Queue names stay as they are (the
 * consumers dispatch on them); each process keeps its queues in its own `--persist-to` directory.
 * The media Worker (a Cloudflare Container) is replaced by scripts/fed-local/media-shim.ts, which
 * forwards to the media container server run on the host (fed-local.sh starts it on :8090); with
 * FED_NO_MEDIA=1 the `MEDIA` bindings are dropped instead (no thumbnails, blurhash or badges).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [envName, host, databaseUrl, setupPassword] = process.argv.slice(2);
if (!envName || !host || !databaseUrl || !setupPassword) {
  console.error("usage: gen-config.mjs <env> <host> <databaseUrl> <setupPassword>");
  process.exit(2);
}
const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
export const WORKERS = ["gateway", "api", "stream", "timeline"];
const prefix = `mkfed-${envName}-`;

/** Drop every `[[services]]` table whose binding is MEDIA. */
function dropMediaService(toml) {
  return toml.replace(/\[\[services\]\]\nbinding = "MEDIA"\nservice = "[^"]+"\n/g, "");
}

const noMedia = process.env.FED_NO_MEDIA === "1";

for (const w of WORKERS) {
  let toml = readFileSync(join(root, "packages", w, "wrangler.toml"), "utf8");
  if (noMedia) toml = dropMediaService(toml);
  toml = toml.replace(/"misskey-cf-/g, `"${prefix}`);
  toml = toml.replace(/^INSTANCE_URL = ".*"$/m, `INSTANCE_URL = "https://${host}"`);
  // Local Postgres instead of the staging Hyperdrive (local-only file, never committed)
  toml = toml.replace(/(\[\[hyperdrive\]\]\nbinding = "HYPERDRIVE"\nid = "[^"]+")/, `$1\nlocalConnectionString = "${databaseUrl}"`);
  if (w === "api") toml = toml.replace(/^\[vars\]$/m, `[vars]\nSETUP_PASSWORD = "${setupPassword}"`);
  // Cron triggers and smart placement mean nothing locally
  toml = toml.replace(/^\[placement\]\nmode = "smart"\n/m, "");
  writeFileSync(join(root, "packages", w, `wrangler.fed-${envName}.toml`), `# generated by scripts/fed-local/gen-config.mjs — do not commit\n${toml}`);
}
if (!noMedia) {
  writeFileSync(
    join(root, "scripts/fed-local", `wrangler.fed-${envName}-media.toml`),
    `# generated by scripts/fed-local/gen-config.mjs — do not commit
name = "${prefix}media"
main = "media-shim.ts"
compatibility_date = "2025-09-01"

[vars]
MEDIA_URL = "${process.env.FED_MEDIA_URL ?? "http://127.0.0.1:8090"}"
`,
  );
}
console.log(`wrote wrangler.fed-${envName}.toml for ${WORKERS.join(", ")}${noMedia ? "" : " + media shim"} (https://${host})`);
