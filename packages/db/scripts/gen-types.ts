/**
 * `pnpm db:gen-types [--check]` — generate src/schema.gen.ts (Kysely table types) by applying the
 * vendored migrations to an in-process PGlite and reading the catalog. No database or upstream
 * checkout needed. Re-run after `pnpm gen-migrations`.
 *
 *   --check: exit 1 when the committed file is stale.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { loadMigrations, migrate } from "../src/migrate.js";

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/schema.gen.ts");
const check = process.argv.includes("--check");

/** Tables that are not part of the application schema. */
const SKIP_TABLES = new Set(["migrations"]);

/** Postgres base type (udt_name without the array `_`) → TS type, as `pg` returns it by default. */
const SCALARS: Record<string, string> = {
  varchar: "string",
  text: "string",
  bpchar: "string",
  uuid: "string",
  inet: "string",
  citext: "string",
  int2: "number",
  int4: "number",
  float4: "number",
  float8: "number",
  int8: "Int8",
  numeric: "Numeric",
  bool: "boolean",
  timestamptz: "Timestamp",
  timestamp: "Timestamp",
  date: "Timestamp",
  json: "Json",
  jsonb: "Json",
  bytea: "Buffer",
};
/** Scalars that are ColumnType wrappers and so cannot be array elements. */
const WRAPPED = new Set(["Int8", "Numeric", "Timestamp", "Json"]);

type Column = { table: string; column: string; nullable: boolean; generated: boolean; udt: string };

function pascal(name: string): string {
  return name.replace(/(^|_)([a-z0-9])/g, (_, _s, c: string) => c.toUpperCase());
}

async function introspect(): Promise<{ columns: Column[]; enums: Map<string, string[]> }> {
  const db = new PGlite();
  await migrate(
    {
      async query(text, params) {
        if (params === undefined) {
          const rs = await db.exec(text);
          return { rows: (rs[rs.length - 1]?.rows ?? []) as Record<string, unknown>[] };
        }
        return { rows: (await db.query<Record<string, unknown>>(text, params)).rows };
      },
    },
    loadMigrations(),
  );
  const cols = await db.query<{ table_name: string; column_name: string; is_nullable: string; column_default: string | null; is_identity: string; udt_name: string }>(
    `SELECT c.table_name, c.column_name, c.is_nullable, c.column_default, c.is_identity, c.udt_name
     FROM information_schema.columns c
     JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
     WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
     ORDER BY c.table_name, c.ordinal_position`,
  );
  const enumRows = await db.query<{ typname: string; label: string }>(
    `SELECT t.typname, e.enumlabel AS label FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
     JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = 'public' ORDER BY t.typname, e.enumsortorder`,
  );
  await db.close();
  const enums = new Map<string, string[]>();
  for (const r of enumRows.rows) enums.set(r.typname, [...(enums.get(r.typname) ?? []), r.label]);
  const columns = cols.rows
    .filter((r) => !SKIP_TABLES.has(r.table_name))
    .map((r) => ({
      table: r.table_name,
      column: r.column_name,
      nullable: r.is_nullable === "YES",
      generated: r.column_default !== null || r.is_identity === "YES",
      udt: r.udt_name,
    }));
  return { columns, enums };
}

function tsType(c: Column, enums: Map<string, string[]>): string {
  const isArray = c.udt.startsWith("_");
  const base = isArray ? c.udt.slice(1) : c.udt;
  const scalar = enums.has(base) ? pascal(base) : SCALARS[base];
  if (!scalar) throw new Error(`gen-types: ${c.table}.${c.column} has unmapped type ${c.udt}`);
  if (isArray && WRAPPED.has(scalar)) throw new Error(`gen-types: ${c.table}.${c.column} is an array of ${scalar}; add a mapping`);
  const t = isArray ? `${scalar}[]` : scalar;
  const n = c.nullable ? `${t} | null` : t;
  return c.generated ? `Generated<${n}>` : n;
}

function render(columns: Column[], enums: Map<string, string[]>): string {
  const lines = [
    "// Generated by packages/db/scripts/gen-types.ts from packages/db/migrations. Do not edit.",
    "// Regenerate with `pnpm db:gen-types` after updating the migrations.",
    "",
    'import type { ColumnType } from "kysely";',
    "",
    "/** Has a database default: optional on insert. (Unlike kysely's own, unwraps ColumnType like kysely-codegen.) */",
    "export type Generated<T> = T extends ColumnType<infer S, infer I, infer U> ? ColumnType<S, I | undefined, U> : ColumnType<T, T | undefined, T>;",
    "/** timestamptz / timestamp / date: `pg` returns Date; ISO strings are accepted on write. */",
    "export type Timestamp = ColumnType<Date, Date | string, Date | string>;",
    "/** int8: `pg` returns bigint columns as strings. */",
    "export type Int8 = ColumnType<string, string | number | bigint, string | number | bigint>;",
    "/** numeric: returned as strings. */",
    "export type Numeric = ColumnType<string, string | number, string | number>;",
    "export type JsonPrimitive = string | number | boolean | null;",
    "export type JsonValue = JsonPrimitive | JsonValue[] | { [key: string]: JsonValue };",
    "/** json / jsonb: parsed on read; write JSON text (see `jsonb()` in kysely.ts). */",
    "export type Json = ColumnType<JsonValue, string, string>;",
    "",
  ];
  for (const [name, labels] of enums) {
    lines.push(`export type ${pascal(name)} = ${labels.map((l) => JSON.stringify(l)).join(" | ")};`);
  }
  lines.push("");
  const tables = [...new Set(columns.map((c) => c.table))];
  for (const table of tables) {
    lines.push(`export interface ${pascal(table)}Table {`);
    for (const c of columns.filter((x) => x.table === table)) {
      const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(c.column) ? c.column : JSON.stringify(c.column);
      lines.push(`  ${key}: ${tsType(c, enums)};`);
    }
    lines.push("}", "");
  }
  lines.push("export interface DB {");
  for (const table of tables) lines.push(`  ${table}: ${pascal(table)}Table;`);
  lines.push("}", "");
  return lines.join("\n");
}

const { columns, enums } = await introspect();
const text = render(columns, enums);
if (check) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("gen-types: packages/db/src/schema.gen.ts is stale (run `pnpm db:gen-types`)");
    process.exit(1);
  }
  console.log("gen-types: schema.gen.ts up to date");
} else {
  writeFileSync(out, text);
  console.log(`gen-types: wrote ${new Set(columns.map((c) => c.table)).size} tables, ${enums.size} enums to packages/db/src/schema.gen.ts`);
}
